#!/usr/bin/env node

import fs from 'fs';

/**
 * Smart velocity governor for Pure Lambda seed generation
 * Automatically switches between conservative and expansive modes
 */

const DEFAULT_CONFIG = {
  conservative: {
    eps: 0.07,
    buckets: { core: 0.45, advanced: 0.35, proof: 0.15, experimental: 0.05 }
  },
  expansive: {
    eps: 0.12,
    buckets: { core: 0.55, advanced: 0.35, proof: 0.10, experimental: 0.10 }
  },
  thresholds: {
    trust_min: 0.95,
    trust_expand: 0.96,
    novelty_min: 0.33,
    novelty_expand: 0.36,
    dedupe_blocks_max: 3,
    dedupe_blocks_expand: 1
  }
};

function readMetrics() {
  let trust = null, novelty = null, dedupeBlocks = 0;

  // Read trust metrics
  try {
    const trustData = JSON.parse(fs.readFileSync('dist/trust.json', 'utf8'));
    trust = trustData.score || null;
  } catch (e) {
    console.warn('⚠️ Could not read trust.json');
  }

  // Read novelty from metrics
  try {
    const metricsData = JSON.parse(fs.readFileSync('dist/metrics.json', 'utf8'));
    novelty = metricsData.novelty?.median || null;
  } catch (e) {
    console.warn('⚠️ Could not read metrics.json');
  }

  // Count dedupe blocks from recent activity (last 24h)
  try {
    // This would be implemented to check recent auto-merge logs or PR labels
    // For now, mock it
    dedupeBlocks = 0;
  } catch (e) {
    console.warn('⚠️ Could not count recent dedupe blocks');
  }

  return { trust, novelty, dedupeBlocks };
}

function determineMode(metrics, config = DEFAULT_CONFIG) {
  const { trust, novelty, dedupeBlocks } = metrics;
  const { thresholds } = config;

  console.log(`📊 Current metrics: Trust=${trust ? (trust * 100).toFixed(1) + '%' : 'n/a'}, Novelty=${novelty ? novelty.toFixed(3) : 'n/a'}, Dedupe blocks=${dedupeBlocks}`);

  // Check if we should expand (all conditions must be met)
  const canExpand =
    trust !== null && trust >= thresholds.trust_expand &&
    novelty !== null && novelty >= thresholds.novelty_expand &&
    dedupeBlocks <= thresholds.dedupe_blocks_expand;

  // Check if we should contract (any condition triggers contraction)
  const shouldContract =
    (trust !== null && trust < thresholds.trust_min) ||
    (novelty !== null && novelty < thresholds.novelty_min) ||
    dedupeBlocks >= thresholds.dedupe_blocks_max;

  if (shouldContract) {
    console.log('📉 CONTRACTING: metrics below safety thresholds');
    return 'conservative';
  } else if (canExpand) {
    console.log('📈 EXPANDING: all metrics green for velocity increase');
    return 'expansive';
  } else {
    console.log('⚖️ MAINTAINING: metrics in stable range');
    return 'conservative'; // Default to conservative when uncertain
  }
}

function updateSweepConfig(mode, config = DEFAULT_CONFIG) {
  const sweepConfigPath = 'configs/sweep.yaml';

  try {
    let sweepConfig = fs.readFileSync(sweepConfigPath, 'utf8');

    const modeConfig = config[mode];
    console.log(`🔧 Updating sweep config for ${mode} mode:`);
    console.log(`   EPS: ${modeConfig.eps}`);
    console.log(`   Buckets: ${JSON.stringify(modeConfig.buckets)}`);

    // Update bucket shares in YAML
    Object.entries(modeConfig.buckets).forEach(([bucket, share]) => {
      const regex = new RegExp(`(${bucket}:\\s*\\n\\s*share:\\s*)([0-9.]+)`, 'g');
      sweepConfig = sweepConfig.replace(regex, `$1${share.toFixed(2)}`);
    });

    // Note: EPS is typically handled in the sweep script itself
    // We could add it to the YAML or pass as environment variable

    fs.writeFileSync(sweepConfigPath, sweepConfig);
    console.log(`✅ Updated ${sweepConfigPath}`);

    // Create environment file for EPS
    const envContent = `# Generated by smart-governor.mjs - ${mode} mode\nEPS=${modeConfig.eps}\nMODE=${mode}\n`;
    fs.writeFileSync('.velocity.env', envContent);
    console.log(`✅ Created .velocity.env with EPS=${modeConfig.eps}`);

    return true;
  } catch (error) {
    console.error(`❌ Failed to update sweep config: ${error.message}`);
    return false;
  }
}

function generateSweep(mode) {
  try {
    const { execSync } = require('child_process');

    console.log(`🌱 Generating seeds in ${mode} mode...`);

    const command = mode === 'expansive'
      ? 'node scripts/generate/sweep.mjs configs/sweep.yaml out/sweep/ --bandit'
      : 'node scripts/generate/sweep.mjs configs/sweep.yaml out/sweep/ --deterministic';

    execSync(command, { stdio: 'inherit' });
    console.log('✅ Seed generation completed');

    return true;
  } catch (error) {
    console.error(`❌ Seed generation failed: ${error.message}`);
    return false;
  }
}

function saveGovernorState(mode, metrics) {
  const state = {
    mode,
    timestamp: new Date().toISOString(),
    metrics,
    nextCheck: new Date(Date.now() + 4 * 60 * 60 * 1000).toISOString() // 4 hours
  };

  try {
    fs.writeFileSync('dist/governor-state.json', JSON.stringify(state, null, 2));
    console.log(`📋 Governor state saved: ${mode} mode`);
  } catch (error) {
    console.warn(`⚠️ Could not save governor state: ${error.message}`);
  }
}

// CLI
async function main() {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const force = args.includes('--force');

  console.log('🎛️ Smart Velocity Governor');
  console.log('=' .repeat(40));

  // Read current metrics
  const metrics = readMetrics();

  // Determine optimal mode
  const mode = determineMode(metrics);

  if (dryRun) {
    console.log(`\n🔍 DRY RUN: Would switch to ${mode} mode`);
    console.log(`Configuration: ${JSON.stringify(DEFAULT_CONFIG[mode], null, 2)}`);
    return;
  }

  // Update configuration
  const configUpdated = updateSweepConfig(mode);
  if (!configUpdated && !force) {
    console.error('❌ Configuration update failed, aborting');
    process.exit(1);
  }

  // Generate seeds
  const sweepSuccess = generateSweep(mode);
  if (!sweepSuccess && !force) {
    console.error('❌ Seed generation failed');
    process.exit(1);
  }

  // Save state
  saveGovernorState(mode, metrics);

  console.log(`\n✅ Smart governor completed: ${mode} mode active`);
}

if (process.argv[1] === new URL(import.meta.url).pathname) {
  main().catch(error => {
    console.error('❌ Governor failed:', error.message);
    process.exit(1);
  });
}

export { determineMode, updateSweepConfig, DEFAULT_CONFIG };